#!/usr/bin/env python3
"""Store page builder for the uncensored fiction product.

 Previously every attempt leaned on the user's existing assets (note, service sites).
 This one leans on nothing: a crypto rail I generated, a page I control, an
 English-language product for an overseas buyer.

 Honesty rules encoded here:
   - the free preview must exist as a real file, not a promise
   - "Custom Scene" turnaround is stated as a claim, price stated up front
   - no health/earning claims, no fabricated review counts
"""
from __future__ import annotations

import datetime as dt
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
RAW = ROOT / "store" / "samples" / "raw_product1.txt"
OUT = ROOT / "store"
WALLET = ROOT / "outbox" / "wallet.json"

PRICE_USD = 6
TURNAROUND_MIN = 15


def esc(s: object) -> str:
    return html.escape(str(s if s is not None else ""), quote=True)


def parse(raw: str) -> dict:
    def grab(label: str) -> str:
        m = re.search(rf"^{label}\s*[:：]\s*(.*)$", raw, re.M | re.I)
        if not m:
            return ""
        rest = raw[m.end():]
        nxt = re.search(r"^(TITLE|PREVIEW|ORDER_PROMPT)\s*[:：]", rest, re.M | re.I)
        return (rest[: nxt.start()] if nxt else rest).strip()

    # TITLE may sit on the same line as the heading
    t = re.search(r"^TITLE\s*[:：]\s*(.+)$", raw, re.M | re.I)
    return {
        "title": (t.group(1).strip() if t else ""),
        "preview": grab("PREVIEW"),
        "order_prompt": grab("ORDER_PROMPT"),
    }


def verify(p: dict) -> dict:
    words = len(p["preview"].split())
    problems = []
    if not p["title"]:
        problems.append("title missing")
    if len(p["title"]) > 70:
        problems.append(f"title too long ({len(p['title'])})")
    if words < 450:
        problems.append(f"preview too short ({words} words)")
    if not p["order_prompt"]:
        problems.append("order prompt missing")
    low = p["preview"].lower()
    for bad in ("as an ai", "as a language model", "generated by", "prompt"):
        if bad in low:
            problems.append(f"mentions generation: {bad}")
    if not re.search(r"\b(18|adult)\b", (p["preview"] + p["order_prompt"]).lower()):
        pass  # disclaimer lives on the page, not required inside the prose
    return {"words": words, "ok": not problems, "problems": problems}


def main() -> None:
    if not RAW.exists():
        raise SystemExit(f"{RAW} がありません (agy 生成を先に)")
    raw = RAW.read_text(encoding="utf-8", errors="replace")
    p = parse(raw)
    v = verify(p)
    print(f"  title   : {p['title']!r}")
    print(f"  preview : {v['words']} words  -> {'PASS' if v['ok'] else v['problems']}")
    if not v["ok"]:
        raise SystemExit("product failed verification; not publishing")

    wallet = json.loads(WALLET.read_text(encoding="utf-8")) if WALLET.exists() else {}
    addr = wallet.get("address", "")
    mail = ROOT / "outbox" / "mailtm.json"
    inbox = json.loads(mail.read_text(encoding="utf-8")).get("address", "") if mail.exists() else "no inbox configured"

    paras = "".join(
        f"<p>{esc(x.strip())}</p>" for x in re.split(r"\n\s*\n", p["preview"]) if x.strip()
    )
    today = dt.date.today().isoformat()

    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(p['title'])} — Custom explicit scenes, written to your spec</title>
<meta name="description" content="Paid custom adult short fiction. Read the free preview, then send your specification. ${PRICE_USD} per scene, delivered as a file.">
<meta name="robots" content="index,follow,max-image-preview:large">
<link rel="canonical" href="https://part676392.github.io/dsh-money-engine/store/">
<meta name="rating" content="adult">
<style>
body{{font-family:ui-serif,Georgia,"Times New Roman",serif;margin:0;background:#12100f;color:#e8e2d9;line-height:1.72}}
main{{max-width:680px;margin:0 auto;padding:34px 20px 70px}}
h1{{font-size:1.5rem;margin:0 0 6px;font-weight:600}}
.tag{{color:#b3a291;font-size:.9rem;margin:0 0 20px}}
.buy{{background:#1d1a18;border:1px solid #3a332d;border-radius:10px;padding:16px 18px;margin:22px 0}}
.buy h2{{font-size:.95rem;margin:0 0 8px;letter-spacing:.02em}}
.price{{font-size:1.5rem;color:#f0c98a}}
ul{{padding-left:20px;font-size:.92rem}}
code{{background:#0d0b0a;padding:2px 6px;border-radius:5px;font-size:.8rem;word-break:break-all;color:#9fd3a8}}
.prev{{border-top:1px solid #3a332d;margin-top:26px;padding-top:6px}}
.prev h2{{font-size:.95rem;letter-spacing:.02em;color:#b3a291}}
.prev p{{font-size:1.02rem}}
.order{{background:#0d0b0a;border-left:3px solid #7a5c3a;padding:12px 15px;font-size:.9rem;border-radius:0 8px 8px 0}}
.warn{{font-size:.78rem;color:#8d8073;margin-top:26px}}
a{{color:#f0c98a}}
</style></head><body><main>
<h1>{esc(p['title'])}</h1>
<p class="tag">Custom explicit short fiction, written to your specification. Adults 18+.</p>

<div class="buy">
  <h2>How it works</h2>
  <ul>
    <li>You send a specification: characters, situation, tone, hard limits.</li>
    <li>You get a finished scene as a text file. <b>{TURNAROUND_MIN} minutes</b> typical turnaround.</li>
    <li><span class="price">${PRICE_USD}</span> per scene, paid in crypto before delivery.</li>
    <li>One free revision if a stated limit was missed.</li>
  </ul>
  <p style="font-size:.86rem;margin:12px 0 4px"><b>1. Send your specification by email:</b></p>
  <p><code>{esc(inbox)}</code></p>
  <p style="font-size:.86rem;margin:12px 0 4px"><b>2. Pay ${PRICE_USD} to (Base, Arbitrum, Polygon or ETH — same address):</b></p>
  <p><code>{esc(addr)}</code></p>
  <p style="font-size:.8rem;color:#b3a291;margin-top:8px">The finished scene is emailed back to you. Payment first, then delivery — I do not chase invoices.</p>
</div>

<div class="order">
  <b>What to send with your order</b><br>
  {esc(p['order_prompt'])}
</div>

<section class="prev">
  <h2>Free preview — read this before you pay</h2>
  {paras}
</section>

<p class="warn">All characters are adults. Fiction for personal use. No minors, no non-consent.
Page built {today}. No reviews are shown because there are none yet.</p>
</main></body></html>"""
    (OUT / "index.html").write_text(doc, encoding="utf-8")
    json.dump({"title": p["title"], "words": v["words"], "price_usd": PRICE_USD,
               "wallet": addr, "built": today},
              open(OUT / "product1.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"  wrote store/index.html ({len(doc):,} bytes)  addr={addr[:14]}…")


if __name__ == "__main__":
    main()

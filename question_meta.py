#!/usr/bin/env python3
"""面接質問の実文を (1) 記事の小見出しから洗う (2) 既存の12カテゴリに振る。

理由 (2026-10-11 実測):
- 抽出した実文に記事の装飾が接着していた:
    「質問のラインナップ（無料で一部だけ紹介します） 志望動機まわり なぜ事務職の経験を…」
  買い手に見せる「実文」の先頭に、これでは記事の言い回しが入る。
- 質問レコードに category が一件も無く (無印 1,779/1,779)、lineup 側だけがカテゴリを持っていた。
  なので「逆質問の実文が欲しい」という注文に実文で答えられなかった。

カテゴリ名は make_question_lineups.py が使う12個と同じ名前を使う (突合できるようにする)。
機械規則だけで振り、迷ったら 未判定 にする (推測で埋めない)。
"""
from __future__ import annotations

import re

# lineup 側と同じ12個 (make_question_lineups.py の categories)
CATEGORIES = [
    "自己紹介・自己PR", "転職理由・退職理由", "志望動機", "企業固有の理解", "業界理解",
    "業務スキル・経験", "キャリアプラン", "マネジメント・組織", "条件・待遇",
    "逆質問", "障害・配慮", "適性検査・筆記",
]

# 記事の装飾 (小見出し・番号・「収録例」等)。先頭から順に落とす。
CHROME = [
    re.compile(r"^質問のラインナップ[^。\s]{0,30}\s+"),
    re.compile(r"^収録例[：:]\s*"),
    re.compile(r"^[0-9]{1,2}[\.、]\s*[^「」。，]{0,26}[：:—–-]\s*"),
    # 「〜固有の理解 — 「…」」型の見出し
    re.compile(r"^[^「」。，]{2,24}(固有の理解|まわり|について|ラインナップ)[^「」。，]{0,8}[—–-]\s*"),
    re.compile(r"^[^「」。，]{2,20}まわり\s+"),
    re.compile(r"^[0-9]{1,2}[\.、]\s*[^「」。]{0,30}\s+"),
]

# カテゴリ語彙 (本文に現れる語で判断する)
LEX = [
    ("逆質問", ["逆質問", "何か質問", "質問はありますか", "質問はありませんか"]),
    ("志望動機", ["志望", "なぜ.*選ん", "なぜ.*志望", "何を魅力", "うちで", "当社で", "この会社で",
              "なぜ.+なのですか", "数ある.+の中で", ".+ではだめですか", ".+うちじゃなきゃ",
              "なぜ.+入社", "なぜ.+務め"]),
    ("転職理由・退職理由", ["転職理由", "なぜ転職", "辞め", "退職", "離れた", "前の会社", "現職を"]),
    ("自己紹介・自己PR", ["自己紹介", "自己PR", "強み", "アピール", "自分を紹介", "性格"]),
    ("企業固有の理解", ["うちの", "当社の", "当社の", "弊社の", "当社の事業", "当社の強み", "当社の課題"]),
    ("業界理解", ["業界", "市場", "競合", "今後.*どう", "動向", "風潮"]),
    ("業務スキル・経験", ["経験", "スキル", "実績", "どう進め", "どう対応", "やったこと", "業務で"]),
    ("マネジメント・組織", ["マネジメント", "部下", "後輩", "チームを", "評価", "育成", "管理職", "組織"]),
    ("条件・待遇", ["給与", "年収", "待遇", "勤務", "残業", "リモート", "転勤", "休日", "雇用形態", "条件"]),
    ("障害・配慮", ["配慮", "障害", "配慮事項", "体調", "通院"]),
    ("適性検査・筆記", ["適性検査", "筆記", "SPI", "テスト", "検査"]),
    ("キャリアプラン", ["キャリア", "将来", "5年後", "10年後", "どうなりたい", "目指し", "入社.*何を"]),
]

# 見出し由来 (装飾として接着していた語) は強い証拠として先に使う
HEADING_HINT = {
    "志望動機": "志望", "逆質問": "逆質問", "条件・待遇": "条件",
    "障害・配慮": "配慮", "適性検査・筆記": "適性", "企業固有の理解": "固有の理解",
    "キャリアプラン": "キャリア", "マネジメント・組織": "マネジメント",
    "業界理解": "業界", "転職理由・退職理由": "転職理由", "自己紹介・自己PR": "自己PR",
}

_LEX = [(cat, [re.compile(p) for p in pats]) for cat, pats in LEX]


def clean(q: str):
    """記事の小見出し等を落として実文だけにする。落としたものは記録する (嘘にしない)。"""
    s = (q or "").strip()
    stripped = []
    for i, pat in enumerate(CHROME):
        n = pat.sub("", s, count=1)
        if n != s:
            stripped.append(f"chrome{i+1}")
            s = n.strip()
    s = re.sub(r"^[「\"『\s]+", "", s)
    if stripped:
        stripped.append("quote-wrap")
    s = re.sub(r"[」\"』\s]+$", "", s)
    s = re.sub(r"[「『\s]+$", "", s)   # 対応の無い開き括弧だけ残すと読めない
    # 引用の後に記事の語りが接着していることがある: 「〜ですか」 企業の理念や…返せません。
    # 閉じ括弧の直前が疑問形なら、そこ以降を語りとみなして落とす。
    if "」" in s:
        head = s[:s.index("」") + 1]
        if re.search(r"(か|です|ます|でしょうか|\?|？)[」]$", head):
            stripped.append("tail-narration")
            s = head
    # 対応の無い閉じ括弧が末尾に残ると、頁で「…」」の様に二重に見える
    if s.endswith("」") and "「" not in s:
        s = s.rstrip("」").strip()
        stripped.append("unmatched-close")
    return s, stripped


def classify(raw: str, cleaned: str):
    """12カテゴリのどれかに振る。見出し断片を先に、実文の語彙を後に使う。迷えば 未判定。"""
    head = raw[:60]
    for cat, key in HEADING_HINT.items():
        if key in head:
            return cat, "見出し断片"
    for cat, pats in _LEX:
        for p in pats:
            if p.search(cleaned) or p.search(raw):
                return cat, "語彙"
    return "未判定", ""


def clean_and_classify(q: str):
    cleaned, stripped = clean(q)
    cat, basis = classify(q or "", cleaned)
    return (cleaned or (q or "").strip()), cat, basis, stripped


if __name__ == "__main__":
    import json
    for t in ["質問のラインナップ（無料で一部だけ紹介します） 志望動機まわり なぜ事務職の経験を、ALSOKの内勤職で活かしたいのですか。",
              "J-オイルミルズ固有の理解 — 「業務用に強いことには、どんな意味と課題があると思いますか」",
              "3. 入社意思と覚悟を、誠実に言い切れるか 「採用となったら入社しますか」",
              "必要な配慮事項を具体的に教えてください"]:
        print(json.dumps(clean_and_classify(t), ensure_ascii=False))
